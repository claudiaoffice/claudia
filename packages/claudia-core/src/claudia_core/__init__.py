"""claudia-core: the kernel shared by claudia composes, computes and creates.

    assets       ImageAsset and ImageImport: the image model every app's objects can hold (E10.8)
    revision     Revision(branch, seq): ids that survive redaction and can branch
    commands     Command, Batch, Setup, registry with schema versions and upcasters
    model        DocumentModel: the interface each app implements; Snapshot
    context      what a command works with while it applies
    region       Region: presence, locks and AI edits written once
    presence     holds that move with the edits
    log          Step and CommandLog: the source of truth
    replay       apply a log to a model, deterministically; replay_collecting for a Document-free call site
    history      per-author undo built from the log
    messages     chat records and ephemeral messages (the three message classes)
    manifest     what a document requires from a server
    store        what the kernel needs from storage (implemented by E2)
    document     Document: ties it all together
    events       what a Document tells its subscribers
    facets       what a style property means: the four facets, the kinds of style, and the slots of everything
                 that can be styled (D303-D305, D312, D315)
    css          the CSS a style may hold: a versioned allow-list, a validator, the text form of a style
    styles       StyleBook and the commands that change it (E1.10)
    lists        ListDef, ListBook, SetListItem and the counting of list items (E9.21)
    schemes      Scheme, LevelFormat, SchemeBook: how the markers of a list are drawn, part of the document (E9.22)
    generated    Toc, ContentsEntry, SetGenerated: tables of contents and agendas, derived from the headings (E9.31)
    paragraphs   Paragraph and Run: styled text and who wrote which part, shared by all three apps (E10.17)
    writing      InsertText, DeleteText, TextCommand: typing into any paragraph, character by character (step G)
    fields       RefField, SetField, FieldsChanged: references in the words, read from what they point at (step H)
    object_texts the words and descriptions of objects as texts a search can look in and replace, for any app
    looks        colours and lengths of a resolved style as values a file format holds (D465)
    shapes       ShapeDefinition: one outline in a 100 by 100 box, the same format in all three apps (E10.7)
    asset_store  AssetStore, AssetKind, AssetsChanged: what objects show and the document keeps once, by id (D1431)
    asset_commands  DefineAsset, UpdateAsset, ForgetAsset: the same three commands for every kind of asset (D1431)
    objects      the shared object layer: ObjectBody, Anchor, VisualObject, ObjectModel and their commands
                 (E10.16); ChartDefinition is the same split applied to a chart's own data (E6.6)
    file_boxes   the text boxes and shapes of an office file as the model holds them (D465)
    file_pictures  the pictures of an office file as image objects: what an app needs to hold one (D464)
    raster       Rasterise and the empty picture that stands in for an SVG nobody can draw (D394)
    page         PageSetup: the paper, orientation, margins and page numbers a document prints on (D904, D917)
    language     the language a document is written in, and SetLanguage (D915, D917)
    turning      how far a turned object reaches, in whole units and from a table of sines (D910)

The kernel contains no spreadbook, text or slide code and does no I/O.
"""

