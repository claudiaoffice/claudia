"""stamp_core_properties: who made a fresh Office file and when, in place of what the library that wrote it says."""

from __future__ import annotations

import pytest

from claudia_opc_io import CORE_PART, stamp_core_properties, utc_second

LIBRARY_CORE = (
    b"<?xml version='1.0' encoding='UTF-8' standalone='yes'?>"
    b'<cp:coreProperties xmlns:cp="http://schemas.openxmlformats.org/package/2006/metadata/core-properties" '
    b'xmlns:dc="http://purl.org/dc/elements/1.1/" xmlns:dcterms="http://purl.org/dc/terms/" '
    b'xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance">'
    b"<dc:title>Budget</dc:title><dc:creator>python-docx</dc:creator><dc:description>generated by python-docx"
    b"</dc:description><cp:lastModifiedBy/><cp:revision>1</cp:revision>"
    b'<dcterms:created xsi:type="dcterms:W3CDTF">2013-12-23T23:15:00Z</dcterms:created>'
    b'<dcterms:modified xsi:type="dcterms:W3CDTF">2013-12-23T23:15:00Z</dcterms:modified></cp:coreProperties>'
)
APP = b"<Properties><Application>Microsoft Macintosh Word</Application><Pages>1</Pages></Properties>"


def stamped(parts=None, **values):
    parts = {CORE_PART: LIBRARY_CORE, "docProps/app.xml": APP} if parts is None else parts
    stamp_core_properties(parts, **values)
    return parts


def text_of(parts, tag):
    core = parts[CORE_PART].decode()
    start = core.find(f"<{tag}")
    if start < 0:
        return None
    return core[core.index(">", start) + 1 : core.index(f"</{tag}>", start)]


def test_who_and_when_come_from_the_document_and_not_from_the_library():
    parts = stamped(created="2026-11-11T17:13:05", creator="ada", modified="2026-11-12T08:00:00+01:00", modifier="bob")
    assert text_of(parts, "dc:creator") == "ada"
    assert text_of(parts, "cp:lastModifiedBy") == "bob"
    assert text_of(parts, "dcterms:created") == "2026-11-11T17:13:05Z"
    assert text_of(parts, "dcterms:modified") == "2026-11-12T07:00:00Z"
    assert b"2013" not in parts[CORE_PART]


def test_what_the_document_does_not_know_is_left_out_and_not_made_up():
    parts = stamped()
    assert text_of(parts, "dc:creator") is None
    assert text_of(parts, "dcterms:created") is None
    assert text_of(parts, "dcterms:modified") is None
    assert text_of(parts, "cp:lastModifiedBy") is None


def test_what_nobody_wrote_about_the_document_goes_and_what_somebody_wrote_stays():
    parts = stamped(creator="ada")
    assert text_of(parts, "dc:description") is None  # the library's "generated by python-docx"
    assert text_of(parts, "dc:title") == "Budget"
    parts = stamped({CORE_PART: LIBRARY_CORE.replace(b"generated by python-docx", b"Our budget")}, creator="ada")
    assert text_of(parts, "dc:description") == "Our budget"


def test_the_program_that_wrote_the_file_is_named():
    assert b"<Application>Claudia</Application>" in stamped(creator="ada")["docProps/app.xml"]
    assert b"<Pages>1</Pages>" in stamped(creator="ada")["docProps/app.xml"]


def test_a_package_without_properties_gets_none_made_and_one_with_properties_but_no_app_part_is_fine():
    parts = {"word/document.xml": b"<w/>"}
    stamp_core_properties(parts, creator="ada")
    assert parts == {"word/document.xml": b"<w/>"}
    parts = {CORE_PART: LIBRARY_CORE}
    stamp_core_properties(parts, creator="ada")
    assert set(parts) == {CORE_PART}


def test_stamping_is_repeatable():
    once = stamped(created="2026-11-11T17:13:05Z", creator="ada")
    again = dict(once)
    stamp_core_properties(again, created="2026-11-11T17:13:05Z", creator="ada")
    assert again == once


def test_a_date_is_one_utc_second_with_a_z():
    assert utc_second("2026-11-11T17:13:05.678") == "2026-11-11T17:13:05Z"
    assert utc_second("2026-11-11T18:13:05+01:00") == "2026-11-11T17:13:05Z"
    with pytest.raises(ValueError, match="not a date"):
        utc_second("yesterday")


def test_a_date_that_is_none_is_none():
    assert utc_second(None) is None
