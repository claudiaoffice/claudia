"""The core properties of an OPC package (``docProps/core.xml``: who made the document, who changed it last, and
when), the same part in Word, Excel and PowerPoint files.

A library that writes a fresh file (python-docx, openpyxl, python-pptx) puts its own name and a date of its own
into it -- "python-docx", 2013 -- which says nothing about the document. :func:`stamp_core_properties` replaces
them with what the document knows about itself; what it does not know is left out, not made up (D147). Only fresh
files are stamped: a file somebody else made keeps what it says (D217, D411)."""

from __future__ import annotations

import re
from datetime import UTC, datetime
from xml.etree import ElementTree

from .package import read_parts, write_parts

#: The part that holds them.
CORE_PART = "docProps/core.xml"
_APP_PART = "docProps/app.xml"
#: The name a file says it was written by.
APPLICATION = "Claudia"

_CP = "http://schemas.openxmlformats.org/package/2006/metadata/core-properties"
_DC = "http://purl.org/dc/elements/1.1/"
_TERMS = "http://purl.org/dc/terms/"
_XSI = "http://www.w3.org/2001/XMLSchema-instance"
_DATE_FORMAT = "%Y-%m-%dT%H:%M:%SZ"
#: What the template of a library puts in ``description`` of every file it writes: nobody wrote it about this document.
_BOILERPLATE = frozenset({"generated by python-docx", "generated using python-pptx", "generated by openpyxl"})
_APPLICATION = re.compile(rb"<Application>[^<]*</Application>")


def utc_second(moment: str | None) -> str | None:
    """``moment`` (ISO 8601; no zone means UTC, as every time the server stamps is) as the UTC second a package says
    it in, ``2026-11-11T17:13:05Z``. ``None`` stays ``None``; :class:`ValueError` when it is not a date."""
    if moment is None:
        return None
    try:
        parsed = datetime.fromisoformat(moment)
    except ValueError:
        raise ValueError(f"{moment!r} is not a date") from None
    if parsed.tzinfo is None:
        parsed = parsed.replace(tzinfo=UTC)
    return parsed.astimezone(UTC).strftime(_DATE_FORMAT)


def stamp_core_properties(
    parts: dict[str, bytes],
    *,
    created: str | None = None,
    creator: str | None = None,
    modified: str | None = None,
    modifier: str | None = None,
) -> None:
    """Say in ``parts`` (a package as :func:`~claudia_opc_io.read_parts` gives it, changed in place) who made the
    document and when, and who changed it last and when, instead of what the writing library put there; the dates are
    ISO 8601. A value that is ``None`` is left out. The description a library writes into every file is taken out; a
    title, subject, keywords or description somebody wrote stays. ``docProps/app.xml``, when there is one, names
    Claudia as the program. A package without ``docProps/core.xml`` gets none."""
    core = parts.get(CORE_PART)
    if core is None:
        return
    for prefix, uri in (("cp", _CP), ("dc", _DC), ("dcterms", _TERMS), ("xsi", _XSI)):
        ElementTree.register_namespace(prefix, uri)
    root = ElementTree.fromstring(core)  # noqa: S314 - the part of a file Claudia has just written itself
    _set(root, f"{{{_DC}}}creator", creator)
    _set(root, f"{{{_CP}}}lastModifiedBy", modifier)
    _set(root, f"{{{_TERMS}}}created", utc_second(created), date=True)
    _set(root, f"{{{_TERMS}}}modified", utc_second(modified), date=True)
    description = root.find(f"{{{_DC}}}description")
    if description is not None and (description.text or "").strip().casefold() in _BOILERPLATE:
        root.remove(description)
    parts[CORE_PART] = ElementTree.tostring(root, encoding="UTF-8", xml_declaration=True)
    if _APP_PART in parts:
        parts[_APP_PART] = _APPLICATION.sub(f"<Application>{APPLICATION}</Application>".encode(), parts[_APP_PART])


def stamp_package(
    data: bytes,
    *,
    created: str | None = None,
    creator: str | None = None,
    modified: str | None = None,
    modifier: str | None = None,
) -> bytes:
    """``data`` (a fresh package) with :func:`stamp_core_properties` applied: the bytes of the same file, saying who
    made the document and when."""
    parts = read_parts(data)
    stamp_core_properties(parts, created=created, creator=creator, modified=modified, modifier=modifier)
    return write_parts(parts)


def _set(root: ElementTree.Element, tag: str, value: str | None, *, date: bool = False) -> None:
    element = root.find(tag)
    if value is None:
        if element is not None:
            root.remove(element)
        return
    if element is None:
        element = ElementTree.SubElement(root, tag)
    element.text = value
    if date:
        element.set(f"{{{_XSI}}}type", "dcterms:W3CDTF")
