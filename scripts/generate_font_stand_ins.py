"""Write the layout library's copy of the font stand-ins from ``claudia_core`` (E3.13): one table for every client.

``uv run python scripts/generate_font_stand_ins.py``          rewrite ``layout/src/fonts/stand-ins.generated.ts``
``uv run python scripts/generate_font_stand_ins.py --check``  fail if the checked-in file is not what this would write

``claudia_core.stand_ins`` owns the facts: the font each generic family stands for, the names CSS uses for a generic
family, and the open fonts that take exactly the room of a common office font; :data:`claudia_fonts.CLOSENESS` has
the words for how close a stand-in is. A server sends the fonts of the generic families and the stand-ins with
``GET /api/fonts``; this copy is what the layout library uses when it is given a catalogue without them (its tests,
an older server), its table of generic names, and the type of the words.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from claudia_core.stand_ins import GENERIC_ALIASES, GENERIC_FONTS, SAME_WIDTHS
from claudia_fonts import CLOSENESS

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "layout" / "src" / "fonts" / "stand-ins.generated.ts"


def _object(mapping: dict[str, str]) -> str:
    lines = [f"  {json.dumps(key)}: {json.dumps(value)}," for key, value in mapping.items()]
    return "{\n" + "\n".join(lines) + "\n}"


def render() -> str:
    """The TypeScript module, as it is checked in."""
    words = " | ".join(json.dumps(word) for word in CLOSENESS)
    return (
        "// Generated by scripts/generate_font_stand_ins.py from claudia_core.stand_ins and\n"
        "// claudia_fonts.CLOSENESS (E3.13).\n"
        "// Do not edit: change the Python side and run `uv run python scripts/generate_font_stand_ins.py`.\n"
        "// A test fails when this file is not what they make.\n"
        "\n"
        "/** How close what a document is shown with is to the font it asks for: the font itself, a font with exactly\n"
        " *  its widths (lines and pages break the same, the letters differ), or another font. */\n"
        f"export type Closeness = {words}\n"
        "\n"
        "/** The words of {@link Closeness}, in order. */\n"
        f"export const CLOSENESS: readonly Closeness[] = [{', '.join(json.dumps(w) for w in CLOSENESS)}]\n"
        "\n"
        "/** The font each CSS generic family stands for, and the last resort (`fallback`). */\n"
        "export const STAND_IN_GENERICS = " + _object(dict(GENERIC_FONTS)) + " as const\n"
        "\n"
        "/** Every name CSS uses for a generic family, lower case, by the family it is shown as. */\n"
        "export const GENERIC_ALIASES: Readonly<Record<string, 'serif' | 'sans-serif' | 'monospace'>> = "
        + _object(dict(GENERIC_ALIASES))
        + "\n"
        "\n"
        "/** Open fonts that take exactly the room of a common office font, by the office font. */\n"
        "export const SAME_WIDTHS: Readonly<Record<string, string>> = " + _object(dict(SAME_WIDTHS)) + "\n"
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the file is out of date")
    args = parser.parse_args(argv)
    text = render()
    if args.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT.relative_to(ROOT)} is out of date: run `uv run python scripts/generate_font_stand_ins.py`")
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
