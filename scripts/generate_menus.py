"""Write the web app's menus and keys from the shared menu definition (UX-35, D360, D1644): one for every client.

``uv run python scripts/generate_menus.py``          rewrite ``web/app/lib/menus.generated.ts`` and the table for
                                                    people, ``claudiaoffice-log/notes/keyboard-shortcuts.md``
``uv run python scripts/generate_menus.py --check``  fail if either checked-in file is not what this would write

The definition (``clients/contract/src/claudia_menus/manifest.py``) gives every app its menus and context menus, each
entry with its words, its rule ("Fits when", D1646) and its key in GTK's notation, and says who listens for the key.
The native shells read it directly (the Linux shell; the Windows and macOS shells through their generated menus); the
web page reads this file and assembles its menus from it (``web/app/lib/menus/assemble.ts``), so the menus of all
clients show the same entries with the same keys, and the page listens for exactly those keys. An action has one key
in every app (a test of the definition).
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MENUS_SRC = ROOT / "clients" / "contract" / "src"  # the menu definition, claudia_menus (D1643)
OUT = ROOT / "web" / "app" / "lib" / "menus.generated.ts"
NOTE = ROOT / "claudiaoffice-log" / "notes" / "keyboard-shortcuts.md"

# GTK key names to the KeyboardEvent.key a browser reports for them
_NAMED = {
    "Up": "ArrowUp",
    "Down": "ArrowDown",
    "Left": "ArrowLeft",
    "Right": "ArrowRight",
    "Return": "Enter",
    "Delete": "Delete",
    "Tab": "Tab",
    "minus": "-",
    "period": ".",
    "comma": ",",
}
# The physical key of a symbol that is not typed the same on every layout (Option+. types ≥ on a Mac)
_CODES = {"period": "Period", "comma": "Comma"}
# Symbols that are typed with Shift: the event says so, so the chord must too
_SHIFTED = {"question": "?", "underscore": "_"}
_MODIFIER = re.compile(r"<(Primary|Shift|Alt|Control)>")  # <Control>: the Control key itself, macOS only (D1616)


def chord_of(accelerator: str) -> dict:
    """``<Primary><Alt>d`` -> ``{"key": "d", "code": "KeyD", "ctrl": true, "alt": true}``.

    ``code`` (the physical key) is given for letters and digits: the page falls back to it when the layout or a
    modifier turned the key into another character (Shift+8 types ``*``, Option+R types ``®`` on a Mac). A
    ``ValueError`` for a key name this does not know, so a new shape is noticed here and not mistranslated."""
    modifiers = _MODIFIER.findall(accelerator)
    name = _MODIFIER.sub("", accelerator)
    chord: dict = {}
    if re.fullmatch(r"[A-Za-z]", name):
        chord["key"], chord["code"] = name.lower(), f"Key{name.upper()}"
    elif re.fullmatch(r"[0-9]", name):
        chord["key"], chord["code"] = name, f"Digit{name}"
    elif re.fullmatch(r"F([1-9]|1[0-2])", name):
        chord["key"] = name
    elif name in _NAMED:
        chord["key"] = _NAMED[name]
        if name in _CODES:
            chord["code"] = _CODES[name]
    elif name in _SHIFTED:
        chord["key"] = _SHIFTED[name]
        modifiers.append("Shift")
    else:
        raise ValueError(f"{accelerator!r}: no browser key is known for {name!r}")
    for modifier, field in (("Primary", "ctrl"), ("Control", "control"), ("Shift", "shift"), ("Alt", "alt")):
        if modifier in modifiers:
            chord[field] = True
    return chord


def _manifest_module():
    if str(MENUS_SRC) not in sys.path:
        sys.path.insert(0, str(MENUS_SRC))
    from claudia_menus import manifest  # (pure data, no GTK: its own docstring says so)

    return manifest


def table() -> dict[str, dict]:
    """``{action id: {"chord": …, "owner": "page" | "shell" | "view", "mac": …}}`` over the three apps, sorted by id;
    ``mac`` only where macOS has a key of its own (D1616)."""
    manifest = _manifest_module()
    keys: dict[str, dict] = {}
    for app in APPS:
        for action in manifest.for_app(app).actions:
            if action.keys.default:
                keys[action.id] = {"chord": chord_of(action.keys.default), "owner": action.key_owner.value}
                if action.keys.macos:  # the web on a Mac uses macOS's own key too (D1648)
                    keys[action.id]["mac"] = chord_of(action.keys.macos)
    return dict(sorted(keys.items()))


APPS = ("composes", "computes", "creates")


def render() -> str:
    """The TypeScript module: the key of every action, then each app's menus, context menus and keys without entry."""
    manifest = _manifest_module()
    lines = [
        "// Generated by scripts/generate_menus.py from the shared menu definition",
        "// (clients/contract/src/claudia_menus/manifest.py; UX-35, D360, D1644). Do not edit: change the definition",
        "// and run `uv run python scripts/generate_menus.py`. A test fails when this file is not what it makes.",
        "import type { KeyChord } from './shortcuts'",
        "",
        "/** Who listens for an action's key: the page (in every client), a native shell itself, or the document view",
        " * and the browser where the key is pressed (Enter, Delete, Tab, the clipboard: shown in the menus, listened",
        " * for by nobody else). */",
        "export type KeyOwner = 'page' | 'shell' | 'view'",
        "",
        "export interface ActionKey {",
        "  chord: KeyChord",
        "  owner: KeyOwner",
        "  /** macOS's own key, where it keeps the chord's for itself (D1616); the web on a Mac uses it (D1648). */",
        "  mac?: KeyChord",
        "}",
        "",
        "export const KEYS: Readonly<Record<string, ActionKey>> = {",
    ]
    for action_id, key in table().items():
        chord = _chord_ts(key["chord"])
        mac = f", mac: {_chord_ts(key['mac'])}" if "mac" in key else ""
        lines.append(f"  '{action_id}': {{ chord: {chord}, owner: '{key['owner']}'{mac} }},")
    lines += [
        "}",
        "",
        "/** An entry in one place: its words and its rule belong to the place (`_here`), its id and kind to the",
        " * action. `kind`: `page` runs on the page; `shell` is the native shell's own (Quit, About on a Mac);",
        " * `editing` is the document view's (the clipboard). */",
        "export interface EntryDef {",
        "  id: string",
        "  label: string",
        "  fits: string",
        "  kind: 'page' | 'shell' | 'editing'",
        "  checkable?: true",
        "}",
        "",
        "export interface SubmenuDef {",
        "  label: string",
        "  items: readonly EntryDef[]",
        "}",
        "",
        "export type PlacedDef = EntryDef | SubmenuDef",
        "",
        "/** A menu of the bar or a context menu: its groups, a line drawn between them. `id`: a context menu's thing",
        " * (`object`), or a menu of the bar's word (`insert`), by which the page names it to a shell (D1645). */",
        "export interface MenuDef {",
        "  id: string",
        "  label: string",
        "  sections: readonly (readonly PlacedDef[])[]",
        "}",
        "",
        "export interface AppDef {",
        "  menus: readonly MenuDef[]",
        "  contexts: readonly MenuDef[]",
        '  /** Actions with a key and no entry (the workbook\'s sheet "Keys without entry"). */',
        "  keysOnly: readonly EntryDef[]",
        "}",
        "",
        "export type AppName = 'composes' | 'computes' | 'creates'",
        "",
        "export const DEFINITIONS: Readonly<Record<AppName, AppDef>> = {",
    ]
    for app in APPS:
        definition = manifest.for_app(app)
        lines.append(f"  {app}: {{")
        lines.append("    menus: [")
        lines += [_menu(menu, "      ", manifest) for menu in definition.menus]
        lines.append("    ],")
        lines.append("    contexts: [")
        lines += [_menu(menu, "      ", manifest) for menu in definition.context_menus]
        lines.append("    ],")
        lines.append("    keysOnly: [" + ", ".join(_entry(a) for a in definition.keys_only) + "],")
        lines.append("  },")
    lines += ["}", ""]
    return "\n".join(lines)


def _entry(action) -> str:
    fields = [
        f"id: {_ts(action.id)}",
        f"label: {_ts(action.label)}",
        f"fits: {_ts(action.fits)}",
        f"kind: {_ts(action.kind.value)}",
    ]
    if action.checkable:
        fields.append("checkable: true")
    return "{ " + ", ".join(fields) + " }"


def _menu(menu, indent: str, manifest) -> str:
    """A menu or a context menu, one line per entry."""
    # a context menu's id names its thing; a menu of the bar is named by its word, as the page tells the shells
    named = menu.id if isinstance(menu, manifest.ContextMenu) else menu.word
    head = f"id: {_ts(named)}, label: {_ts(menu.label)}"
    out = [f"{indent}{{ {head}, sections: ["]
    for section in menu.sections:
        out.append(f"{indent}  [")
        for placed in section:
            if isinstance(placed, manifest.Submenu):
                items = ", ".join(_entry(a) for a in placed.items)
                out.append(f"{indent}    {{ label: {_ts(placed.label)}, items: [{items}] }},")
            else:
                out.append(f"{indent}    {_entry(placed)},")
        out.append(f"{indent}  ],")
    out.append(f"{indent}] }},")
    return "\n".join(out)


_OWNER_WORDS = {"page": "", "shell": "the shell", "view": "the document view or the browser"}
_SHOWN = {"Primary": "Ctrl", "Shift": "Shift", "Alt": "Alt"}
_NAMES = {
    "Up": "↑",
    "Down": "↓",
    "Left": "←",
    "Right": "→",
    "Return": "Enter",
    "Delete": "Del",
    "minus": "-",
    "period": ".",
    "comma": ",",
}
_SYMBOLS = {"question": "?", "underscore": "_"}


def shown(accelerator: str) -> str:
    """``<Primary><Alt>d`` -> ``Ctrl+Alt+D``, as the web menus show it."""
    modifiers = _MODIFIER.findall(accelerator)
    name = _MODIFIER.sub("", accelerator)
    parts = [
        _SHOWN[m] for m in ("Primary", "Shift", "Alt") if m in modifiers and not (m == "Shift" and name in _SYMBOLS)
    ]
    key = _SYMBOLS.get(name) or _NAMES.get(name) or (name.upper() if len(name) == 1 else name)
    return "+".join([*parts, key])


def render_note() -> str:
    """The table for people: every menu entry of every app with its key and who listens for it."""
    manifest = _manifest_module()
    lines = [
        "# Keyboard shortcuts: one table for every app and every client (UX-35, D360)",
        "",
        "Generated by `scripts/generate_menus.py` from the shared menu manifest; do not edit by hand (a test fails",
        "when this is not what the manifest makes). Change a key in `clients/contract/src/claudia_menus/manifest.py`",
        "and run `uv run python scripts/generate_menus.py`. *Who listens*: empty is the page, in every client;",
        "otherwise as named.",
        "On a Mac, Ctrl is Cmd and Alt is Option.",
        "",
    ]
    for app in APPS:
        lines += [f"## {app}", "", "| Menu | Entry | Key | Who listens |", "|---|---|---|---|"]
        for menu in manifest.for_app(app).menus:
            for section in menu.sections:
                for entry in section:
                    items = entry.items if isinstance(entry, manifest.Submenu) else (entry,)
                    prefix = f"{entry.label} ▸ " if isinstance(entry, manifest.Submenu) else ""
                    for action in items:
                        key = shown(action.keys.default) if action.keys.default else "—"
                        who = _OWNER_WORDS[action.key_owner.value]
                        lines.append(f"| {menu.label} | {prefix}{action.label} | {key} | {who} |")
        lines.append("")
    return "\n".join(lines)


def _chord_ts(chord: dict) -> str:
    return "{ " + ", ".join(f"{name}: {_ts(value)}" for name, value in chord.items()) + " }"


def _ts(value: object) -> str:
    """A TypeScript literal of a chord's field."""
    return "true" if value is True else "'" + str(value).replace("\\", "\\\\").replace("'", "\\'") + "'"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the file is out of date")
    args = parser.parse_args(argv)
    files = {OUT: render(), NOTE: render_note()}
    if args.check:
        stale = [path for path, text in files.items() if not path.exists() or path.read_text(encoding="utf-8") != text]
        for path in stale:
            print(f"{path.relative_to(ROOT)} is out of date: run `uv run python scripts/generate_menus.py`")
        return 1 if stale else 0
    for path, text in files.items():
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
