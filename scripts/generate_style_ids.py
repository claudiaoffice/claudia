"""Write each app's default style and the style of a shape's words for the layout library and the web app (CODE-60).

``uv run python scripts/generate_style_ids.py``          rewrite ``layout/src/styles.generated.ts``
``uv run python scripts/generate_style_ids.py --check``  fail if the checked-in file is not what this would write

The names are Python's: each app's model says which style a paragraph has until somebody chooses another
(``DEFAULT_STYLE``), and the object layer says which style the words of a shape have. TypeScript wrote them again by
hand, eleven places for ``'body-text'`` alone. The web app imports them from the layout package, which it uses
already, so there is one generated file and no second copy of the names (tests/test_style_ids_generated.py).
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from claudia_composes.model import DEFAULT_STYLE as COMPOSES_DEFAULT
from claudia_computes.styles import DEFAULT_STYLE as COMPUTES_DEFAULT
from claudia_core.file_boxes import SHAPE_LABEL_STYLE
from claudia_creates.styles import DEFAULT_STYLE as CREATES_DEFAULT

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "layout" / "src" / "styles.generated.ts"


def render() -> str:
    """The file as it must be checked in."""
    return f"""// Generated by scripts/generate_style_ids.py from the apps' models: do not edit.
// Run the script after a change there.

/** The style a paragraph has until somebody chooses another, by app (`DEFAULT_STYLE` of each model). */
export const DEFAULT_STYLE = {{
  composes: '{COMPOSES_DEFAULT}',
  computes: '{COMPUTES_DEFAULT}',
  creates: '{CREATES_DEFAULT}',
}} as const

/** The style of the words in a shape (`SHAPE_LABEL_STYLE` of the object layer): made for a shape's label, not for a
 *  paragraph of a text. */
export const SHAPE_LABEL_STYLE = '{SHAPE_LABEL_STYLE}'
"""


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="only check that the file is current")
    args = parser.parse_args(argv)
    wanted = render()
    if args.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != wanted:
            print(f"{OUT.relative_to(ROOT)} is not what the models say: run scripts/generate_style_ids.py")
            return 1
        return 0
    OUT.write_text(wanted, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
