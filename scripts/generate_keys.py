"""Write the web app's key table from the shared menu manifest (UX-35, D360): one table for every client.

``uv run python scripts/generate_keys.py``          rewrite ``web/app/lib/keys.generated.ts`` and the table for people,
                                                   ``claudiaoffice-log/notes/keyboard-shortcuts.md``
``uv run python scripts/generate_keys.py --check``  fail if either checked-in file is not what this would write

The manifest (``clients/linux/src/claudia_shell_gtk/manifest.py``) gives every menu entry its key in GTK's notation and
says who listens for it. The native shells read it directly (the Linux shell; the Windows and macOS shells through
their generated menus); the web page reads this file, so the menus of all clients show the same key for the same
entry, and the page listens for exactly those keys. An action has one key in every app (a test of the manifest).
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LINUX_SRC = ROOT / "clients" / "linux" / "src"
OUT = ROOT / "web" / "app" / "lib" / "keys.generated.ts"
NOTE = ROOT / "claudiaoffice-log" / "notes" / "keyboard-shortcuts.md"

# GTK key names to the KeyboardEvent.key a browser reports for them
_NAMED = {
    "Up": "ArrowUp",
    "Down": "ArrowDown",
    "Left": "ArrowLeft",
    "Right": "ArrowRight",
    "Return": "Enter",
    "Delete": "Delete",
    "Tab": "Tab",
    "minus": "-",
}
# Symbols that are typed with Shift: the event says so, so the chord must too
_SHIFTED = {"question": "?", "underscore": "_"}
_MODIFIER = re.compile(r"<(Primary|Shift|Alt)>")


def chord_of(accelerator: str) -> dict:
    """``<Primary><Alt>d`` -> ``{"key": "d", "code": "KeyD", "ctrl": true, "alt": true}``.

    ``code`` (the physical key) is given for letters and digits: the page falls back to it when the layout or a
    modifier turned the key into another character (Shift+8 types ``*``, Option+R types ``®`` on a Mac). A
    ``ValueError`` for a key name this does not know, so a new shape is noticed here and not mistranslated."""
    modifiers = _MODIFIER.findall(accelerator)
    name = _MODIFIER.sub("", accelerator)
    chord: dict = {}
    if re.fullmatch(r"[A-Za-z]", name):
        chord["key"], chord["code"] = name.lower(), f"Key{name.upper()}"
    elif re.fullmatch(r"[0-9]", name):
        chord["key"], chord["code"] = name, f"Digit{name}"
    elif re.fullmatch(r"F([1-9]|1[0-2])", name):
        chord["key"] = name
    elif name in _NAMED:
        chord["key"] = _NAMED[name]
    elif name in _SHIFTED:
        chord["key"] = _SHIFTED[name]
        modifiers.append("Shift")
    else:
        raise ValueError(f"{accelerator!r}: no browser key is known for {name!r}")
    for modifier, field in (("Primary", "ctrl"), ("Shift", "shift"), ("Alt", "alt")):
        if modifier in modifiers:
            chord[field] = True
    return chord


def _manifest_module():
    if str(LINUX_SRC) not in sys.path:
        sys.path.insert(0, str(LINUX_SRC))
    from claudia_shell_gtk import manifest  # (pure data, no GTK: its own docstring says so)

    return manifest


def table() -> dict[str, dict]:
    """``{action id: {"chord": …, "owner": "page" | "shell" | "view"}}`` over the three apps, sorted by id."""
    manifest = _manifest_module()
    keys: dict[str, dict] = {}
    for app in ("composes", "computes", "creates"):
        for action in manifest.for_app(app).actions:
            if action.accelerators:
                keys[action.id] = {"chord": chord_of(action.accelerators[0]), "owner": action.key_owner.value}
    return dict(sorted(keys.items()))


def render() -> str:
    """The TypeScript module."""
    lines = [
        "// Generated by scripts/generate_keys.py from the shared menu manifest",
        "// (clients/linux/src/claudia_shell_gtk/manifest.py; UX-35, D360). Do not edit: change the manifest and run",
        "// `uv run python scripts/generate_keys.py`. A test fails when this file is not what the manifest makes.",
        "import type { KeyChord } from './shortcuts'",
        "",
        "/** Who listens for an action's key: the page (in every client), a native shell itself, or the document view",
        " * and the browser where the key is pressed (Enter, Delete, Tab, the clipboard: shown in the menus, listened",
        " * for by nobody else). */",
        "export type KeyOwner = 'page' | 'shell' | 'view'",
        "",
        "export interface ActionKey {",
        "  chord: KeyChord",
        "  owner: KeyOwner",
        "}",
        "",
        "export const KEYS: Readonly<Record<string, ActionKey>> = {",
    ]
    for action_id, key in table().items():
        chord = "{ " + ", ".join(f"{name}: {_ts(value)}" for name, value in key["chord"].items()) + " }"
        lines.append(f"  '{action_id}': {{ chord: {chord}, owner: '{key['owner']}' }},")
    lines += ["}", ""]
    return "\n".join(lines)


_OWNER_WORDS = {"page": "", "shell": "the shell", "view": "the document view or the browser"}
_SHOWN = {"Primary": "Ctrl", "Shift": "Shift", "Alt": "Alt"}
_NAMES = {"Up": "↑", "Down": "↓", "Left": "←", "Right": "→", "Return": "Enter", "Delete": "Del", "minus": "-"}
_SYMBOLS = {"question": "?", "underscore": "_"}


def shown(accelerator: str) -> str:
    """``<Primary><Alt>d`` -> ``Ctrl+Alt+D``, as the web menus show it."""
    modifiers = _MODIFIER.findall(accelerator)
    name = _MODIFIER.sub("", accelerator)
    parts = [
        _SHOWN[m] for m in ("Primary", "Shift", "Alt") if m in modifiers and not (m == "Shift" and name in _SYMBOLS)
    ]
    key = _SYMBOLS.get(name) or _NAMES.get(name) or (name.upper() if len(name) == 1 else name)
    return "+".join([*parts, key])


def render_note() -> str:
    """The table for people: every menu entry of every app with its key and who listens for it."""
    manifest = _manifest_module()
    lines = [
        "# Keyboard shortcuts: one table for every app and every client (UX-35, D360)",
        "",
        "Generated by `scripts/generate_keys.py` from the shared menu manifest; do not edit by hand (a test fails",
        "when this is not what the manifest makes). Change a key in `clients/linux/src/claudia_shell_gtk/manifest.py`",
        "and run `uv run python scripts/generate_keys.py`. *Who listens*: empty is the page, in every client;",
        "otherwise as named.",
        "On a Mac, Ctrl is Cmd and Alt is Option.",
        "",
    ]
    for app in ("composes", "computes", "creates"):
        lines += [f"## {app}", "", "| Menu | Entry | Key | Who listens |", "|---|---|---|---|"]
        for menu in manifest.for_app(app).menus:
            for section in menu.sections:
                for entry in section:
                    items = entry.items if isinstance(entry, manifest.Submenu) else (entry,)
                    prefix = f"{entry.label} ▸ " if isinstance(entry, manifest.Submenu) else ""
                    for action in items:
                        key = shown(action.accelerators[0]) if action.accelerators else "—"
                        who = _OWNER_WORDS[action.key_owner.value]
                        lines.append(f"| {menu.label} | {prefix}{action.label} | {key} | {who} |")
        lines.append("")
    return "\n".join(lines)


def _ts(value: object) -> str:
    """A TypeScript literal of a chord's field."""
    return "true" if value is True else "'" + str(value).replace("\\", "\\\\").replace("'", "\\'") + "'"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the file is out of date")
    args = parser.parse_args(argv)
    files = {OUT: render(), NOTE: render_note()}
    if args.check:
        stale = [path for path, text in files.items() if not path.exists() or path.read_text(encoding="utf-8") != text]
        for path in stale:
            print(f"{path.relative_to(ROOT)} is out of date: run `uv run python scripts/generate_keys.py`")
        return 1 if stale else 0
    for path, text in files.items():
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
