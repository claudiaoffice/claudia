/** The name of Neutralino's binary for this computer (src/platform/host.ts). */
export function neutralinoBinaryName(platform: HostPlatform = hostPlatform(), architecture: string = hostArch): string {
  return platform.neutralinoBinaryName(architecture)
}

export interface FindNeutralinoBinaryOptions {
  /** apps/<app>/, the project `neu update` is pointed at: it writes the binary into `bin/` underneath this. Not
   * checked into the repo; D157 pins the binary and client-library versions together. */
  appDir: string
  env?: Env
  platform?: HostPlatform
  arch?: string
}

/** `$CLAUDIA_NEUTRALINO_BIN`, else `<appDir>/bin/<the platform's binary>` if it exists and may be run, else `null`. (On
 * Windows `accessSync(..., X_OK)` only asks whether the file is there; there is no executable bit.) */
export function findNeutralinoBinary(options: FindNeutralinoBinaryOptions): string | null {
  const env = options.env ?? processEnv
  const explicit = env.CLAUDIA_NEUTRALINO_BIN
  if (explicit) return explicit
  const candidate = join(options.appDir, 'bin', neutralinoBinaryName(options.platform, options.arch))
  try {
    accessSync(candidate, constants.X_OK)
    return candidate
  } catch {
    return null
  }
}

/** The files a window needs: what is generated by `npm run build` and what `neu update` fetches. `null` if all are
 * there, else a message that says which command makes them. */
export function missingFiles(appDir: string, exists: (path: string) => boolean = existsSync): string | null {
  const built = ['index.html', join('shell', 'shell.js'), join('ext', 'core.mjs')].filter((f) => !exists(join(appDir, f)))
  if (built.length > 0) {
    return `This app has not been built (missing ${built.join(', ')} in ${appDir}).\nRun 'npm ci && npm run build' in clients/neutralino.`
  }
  if (!exists(join(appDir, 'js', 'neutralino.js'))) {
    return `Neutralino's client library is missing (${join(appDir, 'js', 'neutralino.js')}).\nFetch it with: cd ${appDir} && npx @neutralinojs/neu update`
  }
  return null
}

/** Sets `name` to `value` (or removes it when `value` is `null`) in `base`, leaving no second spelling of the name:
 * variable names are case-insensitive on Windows, and `process.env` keeps the spelling it was given (`Path`), so
 * setting `PATH` on a plain copy would put two variables into the environment of the child, and which of them it
 * sees is not defined. */
export function environmentWith(base: Record<string, string>, name: string, value: string | null): void {
  for (const key of Object.keys(base)) if (key.toUpperCase() === name.toUpperCase()) delete base[key]
  if (value !== null) base[name] = value
}

function valueOf(base: Readonly<Record<string, string>>, name: string): string | undefined {
  const key = Object.keys(base).find((k) => k.toUpperCase() === name.toUpperCase())
  return key === undefined ? undefined : base[key]
}

/** The environment of the Neutralino process (and so of the core it starts). */
export function buildShellEnvironment(
  options: Options,
  base: Env,
  nodeBinary: string,
  supportsSystemCa: boolean,
): Record<string, string> {
  const environment: Record<string, string> = {}
  for (const [key, value] of Object.entries(base)) if (value !== undefined) environment[key] = value
  const path = valueOf(environment, 'PATH')
  const nodeOptions = valueOf(environment, 'NODE_OPTIONS') ?? ''
  environmentWith(environment, 'CLAUDIA_SHELL_APP', options.app)
  environmentWith(environment, 'CLAUDIA_SHELL_SERVER', options.server !== null ? options.server.origin : null)
  environmentWith(environment, 'CLAUDIA_SHELL_DEBUG', options.debug ? '1' : null)
  // The node that runs this launcher comes first, so a plain `node` in the core's command finds the same one.
  environmentWith(environment, 'PATH', [dirname(nodeBinary), ...(path ? [path] : [])].join(delimiter))
  // Node uses its own list of certificate authorities unless told to use the system's (Node 22.15 and newer; an
  // older Node does not know the flag and would refuse to start with it).
  if (supportsSystemCa && !nodeOptions.includes('--use-system-ca')) {
    environmentWith(environment, 'NODE_OPTIONS', `${nodeOptions} --use-system-ca`.trim())
  }
  return environment
}

/** The Neutralino binary's command line: where the app is, and that its resources are the files in that folder. The page
 * is the one there (`url: "/"` in its neutralino.config.json). Left to itself Neutralino looks in its own binary and
 * for a resources.neu first and logs an error for each (CODE-96, D752). */
export function buildShellCommand(binary: string, appDir: string): string[] {
  return [binary, `--path=${appDir}`, '--res-mode=directory']
}

/** `path` in a form that Neutralino can put into the core's command line, which it splits at spaces and cannot quote:
 * the path itself when it has no whitespace, else its short name if that has none, else `null`. */
export function commandSafePath(path: string, shortName: (path: string) => string | null): string | null {
  if (!/\s/.test(path)) return path
  const short = shortName(path)
  return short !== null && !/\s/.test(short) ? short : null
}

export interface RunDeps {
  spawn?: typeof nodeSpawn
  env?: Env
  appDir?: (app: string) => string
  /** The folder the launcher runs from, which the app folder is found beside (D746); this file's by default. */
  launcherFolder?: string
  nodeBinary?: string
  supportsSystemCa?: boolean
  exists?: (path: string) => boolean
  findBinary?: (appDir: string, env: Env) => string | null
  /** The operating system's ways (src/platform/host.ts); this build's by default. */
  platform?: HostPlatform
  /** The binary a checkout's window is started from (default: the platform's, a .app bundle on a Mac). */
  windowBinary?: (appDir: string, downloaded: string, identity: AppIdentity) => WindowBinary
  /** The short name of a path for the core's command (default: the platform's; on Windows asked of `cmd`). */
  shortName?: (path: string) => string | null
  /** What the installer says about this client (src/packaged.ts); `readPackaged` by default, `null` in a checkout. */
  packaged?: (appDir: string) => Packaged | null
  /** Copies the app's folder to the folder the window runs from (src/packaged.ts's `stageApp` by default). */
  stage?: (appDir: string, target: string) => void
  /** Where a packaged client's window of `app` runs from (default: the platform's). */
  runFolder?: (app: string) => string
  /** Makes `link` a symbolic link to `target` (node in a Mac's run folder; `symlinkSync` by default). */
  linkNode?: (target: string, link: string) => void
  /** Sets the core's command in the app's config (default: in neutralino.config.json). */
  setCommand?: (appDir: string, command: string) => void
  /** Switches the window's web inspector on or off in the app's config (default: in neutralino.config.json). */
  setInspector?: (appDir: string, enabled: boolean) => void
  /** Has Neutralino size the window in logical pixels, or not (default: in neutralino.config.json; UX-81, D749). */
  setLogicalPixels?: (appDir: string, enabled: boolean) => void
  out?: (line: string) => void
  err?: (line: string) => void
}

/** Runs one window to its end. Returns the exit code. */
export async function run(options: Options, deps: RunDeps = {}): Promise<number> {
  const env = deps.env ?? processEnv
  const out = deps.out ?? ((line) => console.log(line))
  const err = deps.err ?? ((line) => console.error(line))
  const platform = deps.platform ?? hostPlatform()
  const identity = getIdentity(options.app) // refuses an app that does not exist, before anything is looked for
  const appDir = (deps.appDir ?? ((app) => appFolder(app, deps.launcherFolder)))(options.app)

  const missing = missingFiles(appDir, deps.exists)
  if (missing !== null) {
    err(missing)
    return 1
  }
  const downloaded = (deps.findBinary ?? ((dir, e) => findNeutralinoBinary({ appDir: dir, env: e, platform })))(appDir, env)
  if (downloaded === null) {
    err(
      `No Neutralino binary found for this computer (expected ${join(appDir, 'bin', neutralinoBinaryName(platform))}).\n` +
        `Fetch it with: cd ${appDir} && npx @neutralinojs/neu update\n` +
        '(it reads the pinned cli.binaryVersion in neutralino.config.json, D157).\n' +
        "Or set CLAUDIA_NEUTRALINO_BIN to an existing binary's path.",
    )
    return 1
  }
  // A packaged client runs from a copy of the app's folder in the person's own folder (src/packaged.ts); a checkout runs
  // from the folder itself. Neutralino starts the core with a command line that has this folder in it (`${NL_PATH}`)
  // and cannot tell a space in a folder name from a space between words: the short name does it where there is one.
  // Read first: an installed app's window binary is taken as it is (never written next to).
  let packaged: Packaged | null
  try {
    packaged = (deps.packaged ?? readPackaged)(appDir)
  } catch (problem) {
    err((problem as Error).message)
    return 1
  }
  if (options.prepare && packaged === null) {
    err('--prepare is for an installed app on a Mac; a checkout opens its window without it.')
    return 1
  }
  // An installed app's binary is taken as it is: on a Mac it is inside the app (claudia <app>.app/Contents/MacOS), which
  // names it (D1626), and nothing is written into an installation.
  let window: WindowBinary
  try {
    window = packaged !== null ? { binary: downloaded } : (deps.windowBinary ?? platform.windowBinary)(appDir, downloaded, identity)
  } catch (problem) {
    err(`Could not prepare this app's window binary: ${(problem as Error).message}`)
    return 1
  }
  let workDir = appDir
  if (packaged !== null) {
    workDir = (deps.runFolder ?? ((app) => platform.runFolder(app, env, env.HOME || homedir())))(options.app)
    try {
      ;(deps.stage ?? stageApp)(appDir, workDir)
    } catch (problem) {
      err(`Could not prepare the folder this window runs from (${workDir}): ${(problem as Error).message}`)
      return 1
    }
  }
  const safeDir = commandSafePath(workDir, deps.shortName ?? ((path) => platform.shortPath(path)))
  if (safeDir === null) {
    err(
      `The folder of the app has a space in its path (${workDir}), and no short name.\n` +
        (packaged !== null ? platform.runFolderWithSpace : 'Move the checkout to a path without spaces and start it again.'),
    )
    return 1
  }
  workDir = safeDir

  const supportsSystemCa = deps.supportsSystemCa ?? process.allowedNodeEnvironmentFlags.has('--use-system-ca')
  const nodeBinary = deps.nodeBinary ?? execPath
  const environment = buildShellEnvironment(options, env, nodeBinary, supportsSystemCa)
  if (packaged !== null) {
    for (const [name, value] of Object.entries(packagedEnvironment(packaged, env))) environmentWith(environment, name, value)
  }
  let nodeForCore = commandSafePath(nodeBinary, deps.shortName ?? ((path) => platform.shortPath(path)))
  if (nodeForCore === null && packaged !== null && platform.linkNodeIntoRun) {
    // No short names on a Mac: a link in the run folder (no space in its path, checked above) names the bundled node.
    nodeForCore = join(workDir, 'node')
    try {
      ;(deps.linkNode ?? symlinkSync)(nodeBinary, nodeForCore)
    } catch (problem) {
      err(`Could not link node into the folder this window runs from (${workDir}): ${(problem as Error).message}`)
      return 1
    }
  }
  if (nodeForCore === null) {
    // No short name either: the core's command cannot hold this path. The launcher already put node's folder first in
    // the PATH of the window, so a plain `node` is the same program -- if Neutralino looks it up there.
    nodeForCore = 'node'
    out(`Note: ${nodeBinary} has a space in it and no short name; the core will be started as a plain 'node' from PATH.`)
  }
  const setCommand = deps.setCommand ?? ((dir, command) => setCoreCommand(join(dir, 'neutralino.config.json'), command, platform.coreCommandKey))
  const inspector = deps.setInspector ?? ((dir, enabled) => setInspector(join(dir, 'neutralino.config.json'), enabled))
  const logicalPixels = deps.setLogicalPixels ?? ((dir, enabled) => setLogicalPixels(join(dir, 'neutralino.config.json'), enabled))
  try {
    setCommand(
      workDir,
      buildCoreCommand({ nodeBinary: nodeForCore, systemCa: supportsSystemCa, app: options.app, server: options.server?.origin ?? null, debug: options.debug }),
    )
    // Neutralino opens the DevTools window by itself when the inspector is on: only --debug wants that.
    inspector(workDir, options.debug)
    // The config's 1280 x 860 are what the page needs as CSS pixels: on Windows Neutralino multiplies them by the display
    // scale only when asked to (D749).
    if (platform.windowSizeInPhysicalPixels) logicalPixels(workDir, true)
  } catch (problem) {
    err(`Could not set up the core's command: ${(problem as Error).message}`)
    return 1
  }
  if (options.debug) {
    out(`app folder: ${workDir}`)
    out(`logs: ${join(stateDir(options.app), 'shell.log')} and ${join(serverStateDir(), 'server.log')}; the web inspector is on`)
  }
  const [shellBinary, ...shellArgs] = buildShellCommand(window.binary, workDir)
  if (options.prepare) {
    // The run folder is a fresh copy at every start: nothing to put back.
    try {
      writeFileSync(join(workDir, WINDOW_SCRIPT), windowScript(environmentChanges(env, environment), [shellBinary as string, ...shellArgs]), { mode: 0o600 })
    } catch (problem) {
      err(`Could not write how to start the window (${join(workDir, WINDOW_SCRIPT)}): ${(problem as Error).message}`)
      return 1
    }
    return 0
  }
  try {
    return await runWindow(shellBinary as string, shellArgs, environment, window.processName, deps, err)
  } finally {
    // The checkout is left as it was found (the checked-in config holds the default command).
    try {
      setCommand(workDir, DEFAULT_COMMAND)
      inspector(workDir, false)
      if (platform.windowSizeInPhysicalPixels) logicalPixels(workDir, false)
    } catch (problem) {
      err(`Could not put the default core command back: ${(problem as Error).message}`)
    }
  }
}

/** The script `--prepare` writes into the run folder; the macOS app's program execs it (D1626). */
export const WINDOW_SCRIPT = 'window.sh'

/** What `environment` sets or removes compared with `base`: `null` for a variable it does not have. */
export function environmentChanges(base: Env, environment: Readonly<Record<string, string>>): Record<string, string | null> {
  const changes: Record<string, string | null> = {}
  for (const [name, value] of Object.entries(environment)) if (base[name] !== value) changes[name] = value
  for (const [name, value] of Object.entries(base)) if (value !== undefined && !(name in environment)) changes[name] = null
  return changes
}

/** `value` as one word of a POSIX shell, whatever it holds. */
export function shellQuote(value: string): string {
  return `'${value.replace(/'/g, `'\\''`)}'`
}

/** A `/bin/sh` script that makes `changes` to its environment and then becomes `command`. */
export function windowScript(changes: Readonly<Record<string, string | null>>, command: readonly string[]): string {
  const lines = ['#!/bin/sh', '# Written by the launcher (--prepare) at every start of this app; the app runs it.']
  for (const [name, value] of Object.entries(changes)) {
    if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(name)) throw new Error(`not a variable a shell can set: ${name}`)
    lines.push(value === null ? `unset ${name}` : `export ${name}=${shellQuote(value)}`)
  }
  lines.push(`exec ${command.map(shellQuote).join(' ')}`)
  return `${lines.join('\n')}\n`
}

function runWindow(
  binary: string,
  args: string[],
  environment: Record<string, string>,
  processName: string | undefined,
  deps: RunDeps,
  err: (line: string) => void,
): Promise<number> {
  const child = (deps.spawn ?? nodeSpawn)(binary, args, {
    stdio: 'inherit',
    env: environment,
    ...(processName !== undefined ? { argv0: processName } : {}),
  })
  // A terminated launcher ends the window too. Ctrl-C reaches both already (they share the terminal or console); this
  // is for `kill`, and SIGHUP is also what Node makes of a closed console window on Windows. Neither signal is real on
  // Windows, where kill() ends the window outright whatever it is given.
  const forward = (signal: NodeJS.Signals) => () => child.kill(signal)
  process.once('SIGTERM', forward('SIGTERM'))
  process.once('SIGHUP', forward('SIGHUP'))
  return new Promise<number>((resolve) => {
    child.once('exit', (code) => resolve(code ?? 0))
    child.once('error', (problem) => {
      err(`Could not start ${binary}: ${problem.message}`)
      resolve(1)
    })
  })
}

function ownVersion(): string {
  try {
    const file = join(dirname(fileURLToPath(import.meta.url)), '..', 'package.json')
    return (JSON.parse(readFileSync(file, 'utf8')) as { version: string }).version
  } catch {
    return 'unknown'
  }
}

/** The whole program: `argv` is what follows `node dist/launch.js` (the app name first). */
export async function main(argv: readonly string[], deps: RunDeps = {}): Promise<number> {
  const err = deps.err ?? ((line) => console.error(line))
  const out = deps.out ?? ((line) => console.log(line))
  const split = splitAppArgument(argv)
  if ('error' in split) {
    err(split.error)
    return 2
  }
  const command = parseCommand(split.app, split.rest, ownVersion())
  if (command.kind === 'print') {
    out(command.text)
    return command.code
  }
  if (command.kind === 'usage_error') {
    err(command.text)
    return command.code
  }
  return run(command.options, deps)
}

// Run as a program, not when imported (by a test or by the bin shims). `pathToFileURL`, not a hand-made `file://`
// string: on Windows `process.argv[1]` is `C:\...\launch.js`, and `file://` + that is not the URL Node reports in
// `import.meta.url`, so the comparison was never true and this program exited at once without a word (third real run
// on a Windows VM, 2026-11-09, notes/e5-11-windows-client.md).
if (processArgv[1] && import.meta.url === pathToFileURL(processArgv[1]).href) {
  main(processArgv.slice(2)).then((code) => {
    process.exitCode = code
  })
}
