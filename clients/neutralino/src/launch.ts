// Starting a window: find the Neutralino binary and the built files of the app, say to the shell which app it is and
// which server it was told to use, and run it. The counterpart of clients/linux/.../launch.py, but much thinner: the
// server, the checks and the settings live in the native core (core.ts), which Neutralino starts together with the
// window (D251), so this launcher knows nothing about servers except the one on the command line.
//
//     node dist/launch.js creates [--server https://demo.claudia-office.de]
//     claudia-creates [--server ...]          (the command npm makes from package.json's `bin`; `.cmd` on Windows)
//
// What it hands to the window: the command that Neutralino runs as the core (core-command.ts), which names the
// absolute path of the node that runs this launcher and carries, as arguments and not as environment, which app this
// window is, which server it was given with --server (as a canonical origin; absent: the core uses the local server of
// the suite) and `--use-system-ca` where Node knows it, so that HTTPS trusts what this computer trusts. The launcher
// puts the command into the app's neutralino.config.json for the run and the default back afterwards.
//
// What is the operating system's own is in src/platform/host.ts (D660): the name of Neutralino's binary, a small .app
// bundle around it on a Mac so the app's name shows, and on Windows the 8.3 short name of node's path, which usually
// has a space in it (`C:\Program Files\nodejs\node.exe`) that Neutralino cannot pass to the core; the launcher falls
// back to a plain `node` from PATH when there is none. Environment variable names are not case-sensitive on Windows,
// and `process.env` keeps the name it was given (`Path`): a copy into a plain object that then sets `PATH` would hold
// both (`environmentWith`), so that is done the careful way everywhere.
//
// An installed app on a Mac (E8.5, D1626) is a launcher script inside `claudia <app>.app` that runs this with
// `--prepare` and then execs the `window.sh` it wrote: the process macOS launched becomes the window itself, so the
// Dock shows one icon with the app's name. `--prepare` does everything up to the window and writes, instead of
// starting it, what differs in the window's environment and the `exec` of the Neutralino inside the app.

